def _read_json(path: Path) -> dict[str, Any] | None:
    """A report file, or None when it has not been written."""
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def current_audit(reports_dir: Path, mode: str, model_version: str) -> dict[str, Any] | None:
    """The group audit of this model version, or None.

    After the model is trained again, fairness.json still describes the older model; its
    groups must not appear next to the new model's numbers.
    """
    fairness = _read_json(reports_dir / mode / REPORT_FILE)
    if fairness is None or fairness["model_version"] != model_version:
        return None
    return fairness


def current_test(reports_dir: Path, mode: str, model_version: str) -> dict[str, Any] | None:
    """The test-period result of this model version, or None."""
    results = _read_json(reports_dir / mode / RESULTS_FILE)
    if results is None or results["model_version"] != model_version:
        return None
    return results


def card_test(results: dict[str, Any] | None, looks: list[dict[str, Any]]) -> dict[str, Any]:
    """The test-period numbers for the card, and how often the test period was used."""
    numbers: dict[str, Any] = {"test_period_looks": float(len(looks))}
    if results is None:
        numbers["test_result"] = (
            "The held-back test period has not been used for this model yet."
        )
        return numbers
    test = results["test"]
    numbers.update(
        test_loans=float(test["loans"]),
        test_share_repaid=_round(test["share_repaid"]),
        test_roc_auc=_round(test["metrics"]["roc_auc"]),
        test_roc_auc_range=_round(test["ranges"]["roc_auc"]),
        test_brier=_round(test["metrics"]["brier"]),
        test_brier_range=_round(test["ranges"]["brier"]),
        test_brier_always_average_rate=_round(results["always_average_rate"]["brier"]),
        test_calibration_error=_round(test["metrics"]["calibration_error"]),
        test_calibration_error_range=_round(test["ranges"]["calibration_error"]),
        test_minus_validation_auc=_round(results["test_minus_validation_auc"]),
    )
    for band, part in results["test_bands"].items():
        key = band.lower().replace(" ", "_")
        numbers[f"test_band_{key}_share"] = _round(part["share"])
        numbers[f"test_band_{key}_share_repaid"] = _round(part["share_repaid"])
    return numbers


def _round(value: Any, digits: int = 6) -> Any:
    """Round a number (or each number of a range) for the card.

    Six decimals: the page shows three, and rounding twice (to four, then to three) can
    change the last digit shown.
    """
    if isinstance(value, float):
        return round(value, digits)
    if isinstance(value, list):
        return [_round(item, digits) for item in value]
    return value


def input_meanings(inputs: list[str], mode: str) -> list[str]:
    """Each model input in words, from the feature dictionary. The card is shown to
    officers too, and officers never see feature names."""
    entries = features_for_mode(load_dictionary(), mode)
    return [entries[name]["definition"] for name in inputs]


def card_metrics(metrics: dict[str, Any], config: dict[str, Any]) -> dict[str, Any]:
    """The numbers and facts of the training report that a reader of the card needs."""
    validation = metrics["validation"]
    point, ranges = validation["metrics"], validation["ranges"]
    simpler = metrics["baselines"]["simpler_model"]
    gain = metrics["gain_over_simpler_model"]
    bands = metrics["validation_bands"]["bands"]
    result: dict[str, Any] = {
        "measured_on": "validation period; the test_ numbers are from the held-back test "
        "period, used once",
        "split": PLAIN.get(metrics["split"]["method"], metrics["split"]["method"]),
        "split_note": metrics["split"]["note"],
        "train_loans": float(metrics["split"]["sizes"]["train"]),
        "validation_loans": float(metrics["split"]["sizes"]["validation"]),
        "model": PLAIN.get(metrics["model"], metrics["model"]),
        "model_choice": metrics["model_choice"]["reason"],
        "calibration": PLAIN.get(
            metrics["calibration"]["method"], metrics["calibration"]["method"]
        ),
        "inputs": INPUT_SEPARATOR.join(
            input_meanings(metrics["inputs_used"], metrics["data_mode"])
        ),
        "share_repaid": _round(validation["share_repaid"]),
        "roc_auc": _round(point["roc_auc"]),
        "roc_auc_range": _round(ranges["roc_auc"]),
        "brier": _round(point["brier"]),
        "brier_range": _round(ranges["brier"]),
        "brier_always_average_rate": _round(
            metrics["baselines"]["always_average_rate"]["brier"]
        ),
        "calibration_error": _round(point["calibration_error"]),
        "calibration_error_range": _round(ranges["calibration_error"]),
        "simpler_model": simpler["description"],
        "simpler_model_roc_auc": _round((simpler.get("metrics") or {}).get("roc_auc")),
        "auc_gain_over_simpler_model": _round(gain.get("auc_gain")),
        "auc_gain_over_simpler_model_range": _round(gain.get("range")),
        "auc_benchmark": config["sanity"]["useful_auc_benchmark"],
    }
    for band, numbers in bands.items():
        key = band.lower().replace(" ", "_")
        result[f"band_{key}_share"] = _round(numbers["share"])
        result[f"band_{key}_share_repaid"] = _round(numbers.get("share_repaid"))
    return result


def card_ablation(ablation: dict[str, Any] | None) -> list[dict[str, Any]]:
    """One row per delivery signal strength: mean AUC of each run and what deliveries add."""
    if ablation is None:
        return []
    rows = []
    for strength, summary in ablation["summary"].items():
        row: dict[str, Any] = {"delivery_signal_strength": float(strength)}
        for run, auc in summary["auc"].items():
            row[f"auc_{run}"] = _round(auc)
        delivery = summary["gain"]["C"]
        row["deliveries_add_mean"] = _round(delivery["mean"])
        row["deliveries_add_lowest"] = _round(delivery["lowest"])
        row["deliveries_add_highest"] = _round(delivery["highest"])
        row["seeds"] = float(summary["seeds"])
        rows.append(row)
    return rows


def card_groups(fairness: dict[str, Any] | None) -> list[dict[str, Any]]:
    """The group audit in flat rows (ranges are left in fairness.json)."""
    if fairness is None:
        return []
    keep = (
        "column", "group", "loans", "share_repaid", "mean_score", "roc_auc", "ranking_gap",
        "ranking", "calibration_gap", "calibration",
    )
    return [
        {key: _round(row[key]) for key in keep if key in row} for row in fairness["groups"]
    ]


def _points(predicted_minus_actual: float) -> str:
    """How far the expected repayment is from what happened, in percentage points."""
    points = round(predicted_minus_actual * 100)
    if points == 0:
        return "about as much repayment as happened"
    way = "more" if points > 0 else "less"
    unit = "point" if abs(points) == 1 else "points"
    return f"{abs(points)} {unit} {way} repayment than happened"


def group_findings(fairness: dict[str, Any] | None) -> list[str]:
    """Plain sentences for every flagged gap, made from the audit's own numbers."""
    if fairness is None:
        return [
            "No group audit has been run for this model version yet: "
            "python -m src.model.fairness"
        ]
    sentences = []
    for row in fairness["groups"]:
        name = f"{COLUMN_NAMES.get(row['column'], row['column'])} '{row['group']}'"
        if row["ranking"] == FLAGGED:
            sentences.append(
                f"Ranking differs for {name} ({row['loans']:,} loans): AUC "
                f"{row['roc_auc']:.2f} against {row['rest_roc_auc']:.2f} for everyone else."
            )
        if row["calibration"] == FLAGGED:
            sentences.append(
                f"Calibration differs for {name} ({row['loans']:,} loans, "
                f"{row['share_repaid']:.0%} repaid): the model expects "
                f"{_points(row['predicted_minus_actual'])} for this group, against "
                f"{_points(row['rest_predicted_minus_actual'])} for everyone else."
            )
    if not sentences:
        seeds = len(fairness["seeds"])
        sentences.append(
            "No group gap was flagged"
            + (f" in any of {seeds} seeds" if seeds > 1 else "")
            + " on these data."
        )
    return sentences


def build_card(mode: str, config: dict[str, Any], reports_dir: Path = REPORTS_DIR) -> dict:
    """The model card of one data mode, as the JSON that GET /model/card serves."""
    metrics = _read_json(reports_dir / mode / METRICS_FILE)
    if metrics is None:
        raise FileNotFoundError(
            f"No training report for '{mode}'. Create it with: python tasks.py train --mode {mode}"
        )
    fairness = current_audit(reports_dir, mode, metrics["model_version"])
    ablation = _read_json(reports_dir / "ablation" / "ablation.json")
    findings = group_findings(fairness)
    numbers = card_metrics(metrics, config)
    test = current_test(reports_dir, mode, metrics["model_version"])
    numbers.update(card_test(test, read_ledger(mode, reports_dir)))
    if test is not None:
        numbers["test_reading"] = TEST_READING[mode]
    numbers.update(
        data_source=SOURCES[mode]["source"],
        terms=SOURCES[mode]["terms"],
        label=SOURCES[mode]["label"],
        banner=banner_text(mode),
        what_this_shows=READING[mode]["shows"],
        what_this_does_not_show=READING[mode]["does_not_show"],
        group_findings=" ".join(findings),
    )
    if mode == SYNTHETIC_MODE and ablation is not None:
        numbers["ablation_runs"] = ABLATION_RUNS
    card = {
        "data_mode": mode,
        "model_version": metrics["model_version"],
        "intended_use": INTENDED_USE if mode == SYNTHETIC_MODE else PUBLIC_USE,
        "metrics": numbers,
        "ablation": card_ablation(ablation) if mode == SYNTHETIC_MODE else [],
        "group_results": card_groups(fairness),
        "limitations": MODE_LIMITS[mode]
        + ([TIME_SPLIT_LIMIT] if metrics["split"]["method"] == "time" else [])
        + COMMON_LIMITS,
    }
    ModelCard.model_validate(card)  # the API must be able to serve it
    return card


def _cell(value: Any) -> str:
    """A table cell: numbers rounded, a range as 'low to high', missing as a dash."""
    if value is None:
        return "-"
    if isinstance(value, list):
        return " to ".join(_cell(item) for item in value)
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def _test_section(m: dict[str, Any], looks: list[dict[str, Any]]) -> list[str]:
    """The held-back test period next to the validation period, and the ledger."""
    lines = ["## Results on the held-back test period", ""]
    if "test_roc_auc" not in m:
        return lines + [m["test_result"], ""]
    lines += [
        "| Measure | Validation | Test | Test 95% range |",
        "|---|---|---|---|",
        f"| AUC | {_cell(m['roc_auc'])} | {_cell(m['test_roc_auc'])} "
        f"| {_cell(m['test_roc_auc_range'])} |",
        f"| Brier score | {_cell(m['brier'])} | {_cell(m['test_brier'])} "
        f"| {_cell(m['test_brier_range'])} |",
        f"| Calibration error | {_cell(m['calibration_error'])} "
        f"| {_cell(m['test_calibration_error'])} | {_cell(m['test_calibration_error_range'])} |",
        "",
        f"{m['test_loans']:,.0f} test loans, {m['test_share_repaid']:.1%} repaid. Brier score "
        f"of always predicting the training average on them: "
        f"{_cell(m['test_brier_always_average_rate'])}. Test bands: "
        + ", ".join(
            f"{band.replace('_', ' ')} {m[f'test_band_{band}_share']:.0%}"
            for band in ("strong", "review", "needs_more_info")
            if f"test_band_{band}_share" in m
        )
        + ". The model, its calibration and the band lines were fixed before this look and "
        "were not changed after it.",
        "",
        f"**Reading.** {m['test_reading']}",
        "",
    ]
    earlier = [entry for entry in looks if not entry["purpose"].startswith("final report")]
    lines.append(
        f"The ledger `reports/<mode>/test_set_use.json` has {len(looks)} "
        f"entr{'y' if len(looks) == 1 else 'ies'} for this test period (one entry can cover "
        "several looks; its detail says)."
        + (
            " Earlier uses: " + "; ".join(entry["purpose"] for entry in earlier) + "."
            if earlier
            else ""
        )
    )
    return lines + [""]


