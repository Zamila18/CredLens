def choice_reason(gain: dict[str, Any], checks: dict[str, bool], needed: float) -> str:
    """The model choice in one Bangla sentence (src/model/train.py `choice_reason`)."""
    failed = [FAILED_CHECK_WORDS[name] for name, passed in checks.items() if not passed]
    numbers = (
        f"লজিস্টিক রিগ্রেশনের চেয়ে LightGBM {gain['auc_gain']:+.4f} AUC যোগ করে (সীমা "
        f"{gain['range'][0]:+.4f} থেকে {gain['range'][1]:+.4f})। এটি তখনই ব্যবহার হয়, যখন পুরো "
        f"সীমা {needed:+.4f}-এ পৌঁছায় এবং এর Brier স্কোর খারাপ নয়।"
    )
    if failed:
        return f"{numbers} এখানে {' এবং '.join(failed)}, তাই লজিস্টিক রিগ্রেশনই থাকে।"
    return f"{numbers} দুটিই খাটে, তাই LightGBM ব্যবহার হয়।"


def _points(predicted_minus_actual: float) -> str:
    points = round(predicted_minus_actual * 100)
    if points == 0:
        return "যা ঘটেছে প্রায় ততটাই পরিশোধ আশা করে"
    return f"যা ঘটেছে তার চেয়ে {abs(points)} পয়েন্ট {'বেশি' if points > 0 else 'কম'} পরিশোধ আশা করে"


def group_findings(fairness: dict[str, Any] | None, flagged: str, value_words: Any) -> list[str]:
    """The flagged gaps in Bangla (src/model/model_card.py `group_findings`).

    Args:
        fairness: the group audit of this model version, or None.
        flagged: the audit's "flagged" status word.
        value_words: turns a group value into words (town tiers and shop types).
    """
    if fairness is None:
        return ["এই মডেল সংস্করণের জন্য এখনও দলভিত্তিক অডিট চালানো হয়নি: python -m src.model.fairness"]
    sentences = []
    for row in fairness["groups"]:
        column = COLUMN_NAMES.get(row["column"], row["column"])
        name = f"{column} '{value_words(row['group'])}'"
        if row["ranking"] == flagged:
            sentences.append(
                f"{name} ({row['loans']:,}টি ঋণ)-এর ক্ষেত্রে ক্রম আলাদা: AUC {row['roc_auc']:.2f}, "
                f"বাকি সবার {row['rest_roc_auc']:.2f}।"
            )
        if row["calibration"] == flagged:
            sentences.append(
                f"{name} ({row['loans']:,}টি ঋণ, {row['share_repaid']:.0%} পরিশোধ)-এর ক্ষেত্রে "
                f"ক্যালিব্রেশন আলাদা: মডেল এই দলের জন্য {_points(row['predicted_minus_actual'])}, "
                f"বাকি সবার জন্য {_points(row['rest_predicted_minus_actual'])}।"
            )
    if not sentences:
        seeds = len(fairness["seeds"])
        where = f"{seeds}টি সিডের কোনোটিতেই " if seeds > 1 else ""
        sentences.append(f"এই ডেটায় {where}কোনো দলের ফারাক চিহ্নিত হয়নি।")
    return sentences


